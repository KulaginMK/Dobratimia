/** started — слушаем; denied — доступа к микрофону нет; failed — микрофон есть, но включить не удалось. */
export type MeterStart = 'started' | 'denied' | 'failed';

/**
 * Измеритель громкости. Голос не записывается (CLAUDE.md, правило 5): отсчёты с микрофона живут
 * в памяти доли секунды — пока из них считается громкость — и никуда не сохраняются и не отправляются.
 * На телефоне — поток expo-audio (useLoudnessMeter.ts), в вебе — Web Audio API (useLoudnessMeter.web.ts).
 */
export type LoudnessMeter = {
  /** Спрашивает доступ к микрофону, если его ещё нет, и начинает слушать. */
  start: () => Promise<MeterStart>;
  /** Громкость звука с прошлого вызова: RMS отсчётов в −1…1. null — нового звука пока не было. */
  read: () => number | null;
  stop: () => void;
  /** Сообщает, когда доступ к микрофону появился: человек разрешил его в настройках. Возвращает отписку. */
  watchAccess: (onGranted: () => void) => () => void;
};
