/**
 * Отметки «Нравится» (таблица likes, docs/08). Пользователь видит и меняет только свои.
 * Специалист видит лишь число отметок; кто их поставил — не видит никто.
 */
export interface LikesRepo {
  /** id специалистов, отмеченных пользователем, с учётом ещё не отправленных отметок. Без сети — последние известные. */
  list(userId: string): Promise<string[]>;
  /**
   * Поставить или снять отметку. Без сети она не теряется: запоминается на устройстве и уходит на сервер позже,
   * а промис отклоняется с OfflineError — экран показывает «Нет интернета» и «Повторить» (docs/08, «Без сети»).
   */
  add(userId: string, specialistId: string): Promise<void>;
  remove(userId: string, specialistId: string): Promise<void>;
  /** Отправить отметки, поставленные без сети. Отклоняется с OfflineError, если сети всё ещё нет. */
  flush(userId: string): Promise<void>;
}
